import assert from 'node:assert/strict';
import Module, { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const require = createRequire(import.meta.url);
require('./model-fixture').seedModels();
const uri = file => ({ fsPath: file, toString: () => file });
const originalLoad = Module._load;
Module._load = function (request, parent, isMain) {
  if (request === 'vscode') return { env: { language: 'en' }, Uri: { file: uri, joinPath: (base, ...parts) => uri(path.join(String(base), ...parts)) }, workspace: { getConfiguration: () => ({ get: (_key, fallback) => fallback }) } };
  return originalLoad.call(this, request, parent, isMain);
};
const { ChatWindowHost } = require('../extension');
Module._load = originalLoad;
const media = path.resolve(fileURLToPath(new URL('../media/', import.meta.url)));
const origin = 'http://127.0.0.1';
const host = Object.assign(Object.create(ChatWindowHost.prototype), { extensionUri: '/panel', panel: {}, deps: { getModels: () => ({}) }, run: null, activeModelId: 'auto', activeAgent: 'auto', lastRoutedAgent: 'codex' });
const html = host.renderHtml({ cspSource: origin, asWebviewUri: value => origin + '/' + path.relative('/panel/media', value.fsPath).replaceAll('\\', '/') });
const browser = await chromium.launch({ headless: true, channel: process.platform === 'win32' ? 'msedge' : undefined });
try {
  const page = await browser.newPage({ viewport: { width: 1000, height: 720 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route(`${origin}/**`, route => {
    const pathname = new URL(route.request().url()).pathname;
    const file = path.resolve(media, '.' + pathname);
    if (pathname === '/') return route.fulfill({ contentType: 'text/html', body: html });
    if (!file.startsWith(media + path.sep) || !fs.existsSync(file)) return route.fulfill({ status: 404 });
    return route.fulfill({ contentType: file.endsWith('.css') ? 'text/css' : file.endsWith('.js') ? 'text/javascript' : 'application/octet-stream', body: fs.readFileSync(file) });
  });
  await page.addInitScript(() => {
    window.sent = []; window.saved = {};
    window.acquireVsCodeApi = () => ({ postMessage: message => window.sent.push(message), getState: () => window.saved, setState: state => { window.saved = state; } });
  });
  await page.goto(origin);
  const open = () => page.locator('#modelPill').click();
  const choice = id => page.locator(`.model-option[data-model-id="${id}"]`);
  const mode = () => page.evaluate(() => window.sent.filter(message => message.type === 'setRoutingMode').at(-1)?.mode);
  await open();
  assert.equal(await page.locator('.model-routing').count(), 0);
  assert.deepEqual(await page.locator('.model-group').first().locator('.model-option-label').allTextContents(), ['Auto']);
  assert.equal(await choice('shadow').count(), 0);
  const model = await page.locator('.model-option').nth(1).getAttribute('data-model-id');
  const modelLabel = await choice(model).locator('.model-option-label').textContent();
  await choice(model).click();
  assert.equal(await mode(), 'manual');
  await open();
  assert.equal(await choice(model).getAttribute('aria-selected'), 'true');
  await choice('auto').click();
  assert.equal(await mode(), 'auto');
  assert.equal(await page.locator('.model-picker-label').textContent(), 'Auto');
  await open();
  await choice(model).click();
  assert.equal(await mode(), 'manual');
  assert.equal(await page.locator('.model-picker-label').textContent(), modelLabel);
  await page.evaluate(() => window.postMessage({ type: 'voiceResult', output: { cleanedPrompt: 'Fix the spacing', decision: { targetModel: 'gemini' } } }, '*'));
  assert.equal(await page.locator('.model-picker-label').textContent(), modelLabel, 'dictation preserves a manually selected model');
  await open();
  await choice('auto').click();
  await page.evaluate(() => window.postMessage({ type: 'voiceResult', output: { cleanedPrompt: 'Fix the parser', decision: { targetModel: 'codex' } } }, '*'));
  assert.equal(await page.locator('.model-picker-label').textContent(), 'Auto', 'legacy voice decisions cannot bypass the current Auto router');
  await open();
  await choice(model).click();
  await page.evaluate(() => window.postMessage({ type: 'routingMode', mode: 'shadow', connected: { cloudflare: true, groq: false } }, '*'));
  assert.equal(await page.locator('.model-picker-label').textContent(), modelLabel);
  await page.evaluate(() => window.postMessage({ type: 'routingMode', mode: 'manual' }, '*'));
  assert.equal(await page.locator('.model-picker-label').textContent(), modelLabel);
  const routing=require('../lib/routing').config({models:{[model]:{tasks:['visual']}}});
  await page.evaluate(snapshot=>window.postMessage({type:'fleet',models:[],services:{routing:snapshot}},'*'),{config:routing,models:[{id:model,agent:'codex',label:modelLabel}],connected:{},usage:{},reset:new Date().toISOString()});
  await page.evaluate(()=>window.postMessage({type:'openSettings',tab:'routing'},'*'));
  await page.locator('[data-key="g:profiles"] > summary').click();
  await page.locator('[data-key="profile:visual"] > summary').click();
  const name=page.getByRole('textbox',{name:'Profile name visual',exact:true});
  await name.fill('Appearance work');await name.blur();
  assert.equal(await page.evaluate(()=>window.sent.filter(m=>m.type==='routingSave').at(-1).config.task_profiles.visual.label),'Appearance work');
  await page.getByRole('button',{name:'Open config',exact:true}).click();
  assert.equal(await page.evaluate(()=>window.sent.at(-1).type),'openRoutingConfig');
  await page.getByRole('button',{name:'Edit with AI',exact:true}).click();
  assert.equal(await page.evaluate(()=>window.sent.at(-1).type),'editRoutingConfigWithAI');
  await page.evaluate(()=>window.postMessage({type:'prefillPrompt',routingConfig:true,text:'Adjust my routing preferences'},'*'));
  assert.equal(await page.locator('#settingsModal').isVisible(),false);
  assert.equal(await page.locator('#promptInput').inputValue(),'Adjust my routing preferences');
  const orchestrator = { id: 'gemini-pro-orchestrator-g1-pro', agent: 'gemini', model: 'gemini-pro-orchestrator-g1-pro', label: 'Orchestrator (Argon)', shortLabel: 'Orchestrator', brand: 'antigravityArgon' };
  await page.evaluate((entry) => window.postMessage({ type: 'modelCatalog', catalog: [entry], available: [entry] }, '*'), orchestrator);
  await open();
  await choice(orchestrator.id).click();
  assert.equal(await page.locator('.model-picker-label').innerText(), 'Orchestrator (Argon)');
  await page.setViewportSize({ width: 480, height: 720 });
  assert.equal(await page.locator('.model-picker-label').innerText(), 'Orchestrator', 'narrow composer hides (Argon) and keeps Orchestrator');
  assert.deepEqual(errors, []);
  console.log('Model picker: Auto, manual selection and legacy mode compatibility passed.');
} finally {
  await browser.close();
}
