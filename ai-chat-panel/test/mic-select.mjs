import assert from 'node:assert/strict';
import Module, { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const require = createRequire(import.meta.url);
require('./model-fixture').seedModels();
const uri = file => ({ fsPath: file, toString: () => file });
const originalLoad = Module._load;
Module._load = function (request, parent, isMain) {
  if (request === 'vscode') return { env: { language: 'en' }, Uri: { file: uri, joinPath: (base, ...parts) => uri(path.join(String(base), ...parts)) }, workspace: { getConfiguration: () => ({ get: (_key, fallback) => fallback }) } };
  return originalLoad.call(this, request, parent, isMain);
};
const { ChatWindowHost } = require('../extension');
Module._load = originalLoad;
const media = path.resolve(fileURLToPath(new URL('../media/', import.meta.url)));
const shotDir = fileURLToPath(new URL('../../out/screenshots/', import.meta.url));
fs.mkdirSync(shotDir, { recursive: true });
const origin = 'http://127.0.0.1';
const host = Object.assign(Object.create(ChatWindowHost.prototype), { extensionUri: '/panel', panel: { sidebar: true }, deps: { getModels: () => ({}) }, run: null, activeModelId: 'auto', activeAgent: 'auto', lastRoutedAgent: 'codex' });
const html = host.renderHtml({ cspSource: origin, asWebviewUri: value => origin + '/' + path.relative('/panel/media', value.fsPath).replaceAll('\\', '/') });
const browser = await chromium.launch({ headless: true, channel: process.platform === 'win32' ? 'msedge' : undefined });
try {
  const page = await browser.newPage({ viewport: { width: 560, height: 900 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route(`${origin}/**`, route => {
    const pathname = new URL(route.request().url()).pathname;
    const file = path.resolve(media, '.' + pathname);
    if (pathname === '/') return route.fulfill({ contentType: 'text/html', body: html });
    if (!file.startsWith(media + path.sep) || !fs.existsSync(file)) return route.fulfill({ status: 404 });
    return route.fulfill({ contentType: file.endsWith('.css') ? 'text/css' : file.endsWith('.js') ? 'text/javascript' : file.endsWith('.svg') ? 'image/svg+xml' : 'application/octet-stream', body: fs.readFileSync(file) });
  });
  await page.addInitScript(() => {
    window.sent = [];
    window.acquireVsCodeApi = () => ({ postMessage(message) { window.sent.push(message); }, getState: () => ({}), setState() {} });
  });
  await page.goto(origin);
  await page.locator('#stopBtn').waitFor({ state: 'attached' });
  const send = message => page.evaluate(data => window.dispatchEvent(new MessageEvent('message', { data })), message);
  const groq = { source: 'account', masked: 'gsk_…abcd', limits: {}, today: { calls: 3 } };
  const voice = { hotkey: 'Ctrl+Alt+Space', mode: 'toggle', sounds: true, micDevice: '', hotkeyActive: true, supported: true, groq };
  await send({ type: 'openSettings', tab: 'voice' });
  await send({ type: 'fleet', models: [], clis: {}, services: { voice } });
  const pauseMedia = page.getByRole('switch', { name: 'Pause background media', exact: true });
  assert.equal(await pauseMedia.getAttribute('aria-checked'), 'true', 'media pause defaults to on');
  await pauseMedia.click();
  assert.equal(await pauseMedia.getAttribute('aria-checked'), 'false');
  assert.deepEqual(await page.evaluate(() => window.sent.filter(m => m.type === 'setVoicePauseMedia')), [{ type: 'setVoicePauseMedia', enabled: false }]);
  await send({ type: 'voice', voice: { ...voice, pauseMedia: false } });
  assert.equal(await pauseMedia.getAttribute('aria-checked'), 'false', 'saved setting survives refresh');
  await pauseMedia.click();
  assert.equal(await pauseMedia.getAttribute('aria-checked'), 'true');
  assert.equal(await page.evaluate(() => window.sent.some(m => m.type === 'requestMicDevices')), true, 'the voice tab asks for devices');
  await send({ type: 'micDevices', devices: ['Microphone (Yeti Stereo)', 'Headset (WH-1000XM5 Hands-Free)'], automatic: 'Microphone (Yeti Stereo)' });
  const root = page.locator('[data-role="micSelect"]');
  const trigger = root.locator('.cs-dd-trigger');
  const options = root.locator('.cs-dd-option');
  assert.equal(await trigger.innerText(), 'Automatic (Microphone (Yeti Stereo))', 'Automatic names the microphone Windows picked');
  await trigger.click();
  assert.deepEqual(await options.allInnerTexts(), ['Automatic (Microphone (Yeti Stereo))', 'Microphone (Yeti Stereo)', 'Headset (WH-1000XM5 Hands-Free)']);
  assert.equal(await root.locator('.cs-dd-menu').isVisible(), true);
  await page.screenshot({ path: process.env.SHOT || path.join(shotDir, 'mic-select.png') });
  await options.nth(1).click();
  assert.equal(await root.locator('.cs-dd-menu').isVisible(), false);
  assert.equal(await trigger.innerText(), 'Microphone (Yeti Stereo)');
  assert.deepEqual(await page.evaluate(() => window.sent.filter(m => m.type === 'setVoiceMic')), [{ type: 'setVoiceMic', device: 'Microphone (Yeti Stereo)' }]);
  await trigger.focus();
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('Enter');
  assert.equal(await trigger.innerText(), 'Headset (WH-1000XM5 Hands-Free)');
  await trigger.click();
  await page.keyboard.press('Escape');
  assert.equal(await root.locator('.cs-dd-menu').isVisible(), false);
  await send({ type: 'voice', voice: { ...voice, micDevice: 'Old USB Mic' } });
  assert.equal(await trigger.innerText(), 'Old USB Mic (not connected)');
  assert.match(await page.locator('[data-role="micDesc"]').innerText(), /not connected/);
  await send({ type: 'micDevices', devices: [] });
  await send({ type: 'voice', voice });
  assert.match(await page.locator('[data-role="micDesc"]').innerText(), /No microphone found/);
  assert.deepEqual(errors, []);
  console.log('mic select ok');
} finally { await browser.close(); }
